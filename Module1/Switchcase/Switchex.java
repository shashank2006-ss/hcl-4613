package Switchcase;

public class Switchex {
    static void main(String[] args) {
        int day=2;
        switch (day){
            case 1:
                System.out.println("mon");
                break;

            case 2:
                System.out.println("tue");
                break;

            default:
                System.out.println("invalid");

        }
    }
}
